var (
	reHumanRaw = regexp.MustCompile(`^a\d{3}_(.*)__(\w+)$`)
	reHumanDig = regexp.MustCompile(`^d\d{3}_(.*)__(\w+)$`)
)

// Subsystem — к какой подсистеме относится признак (subsystem() в Python).
func Subsystem(col string) string {
	if d, ok := Descs[col]; ok {
		return d.Subsystem
	}
	if d, ok := kpsStepDesc(col); ok {
		return d.Subsystem
	}
	switch {
	case strings.HasPrefix(col, "a"):
		return "Сырые аналоговые"
	case strings.HasPrefix(col, "d"):
		return "Дискретные"
	}
	return "Прочее"
}

// Human — понятное название признака (human() в Python): из словаря или из имени канала.
func Human(col string) string {
	if d, ok := Descs[col]; ok {
		return d.Text
	}
	if d, ok := kpsStepDesc(col); ok {
		return d.Text
	}
	if m := reHumanRaw.FindStringSubmatch(col); m != nil {
		return strings.ReplaceAll(m[1], "_", " ") + " [" + m[2] + "]"
	}
	if m := reHumanDig.FindStringSubmatch(col); m != nil {
		kind := "кол-во включений"
		if m[2] == "on" {
			kind = "доля вкл."
		}
		return strings.ReplaceAll(m[1], "_", " ") + " [" + kind + "]"
	}
	return col
}
