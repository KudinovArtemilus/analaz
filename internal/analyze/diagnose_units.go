// none — «порога нет» (None в Python).
var none = math.NaN()

// Indicator — один показатель узла: какой признак, в какую сторону плохо и пороги.
type Indicator struct {
	Feat, Label string
	Bad         string  // "up" — плохо, когда растёт; "down" — когда падает; "both" — любое отклонение
	WarnRel     float64 // относительное отклонение от нормы для «наблюдать» (0,15 = 15%)
	AlarmRel    float64 // … для «проблема»
	AbsWarn     float64 // абсолютный порог (NaN — нет)
	AbsAlarm    float64
	Unit        string
}

// Unit — узел пресса: насос, регулятор, клапан, зажим штампа…
type Unit struct {
	Name, Group string
	Ind         []Indicator
	PeerKind    string // "casedrain" или "pivot" — сравнивать с однотипными узлами
	PeerFeat    string
	SpikeFeat   string // считать выбросы этого признака (сервоклапаны)
	SpikeLabel  string
	Clamp       bool // зажим штампа: особый разбор по периодам между заменами штампа
	Cause       string
	Check       string
}

func ind(feat, label, bad string, warn, alarm float64, unit string) Indicator {
	return Indicator{feat, label, bad, warn, alarm, none, none, unit}
}

func indAbs(feat, label, bad string, warn, alarm, absWarn, absAlarm float64, unit string) Indicator {
	return Indicator{feat, label, bad, warn, alarm, absWarn, absAlarm, unit}
}

